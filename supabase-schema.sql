create table if not exists public.products (
 id bigint generated by default as identity primary key,
 owner_id uuid not null references auth.users(id) on delete cascade,
 name text not null check (char_length(name) between 1 and 120),
 price numeric(12,2) not null default 0 check (price >= 0),
 stock integer not null default 0 check (stock >= 0),
 created_at timestamptz not null default now()
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 owner_id uuid not null references auth.users(id) on delete cascade,
 customer_name text not null check (char_length(customer_name) between 1 and 120),
 amount numeric(12,2) not null default 0 check (amount >= 0),
 status text not null default 'pending' check (status in ('pending','processing','completed','cancelled')),
 created_at timestamptz not null default now()
);
alter table public.products enable row level security;
alter table public.orders enable row level security;
drop policy if exists "Users manage their own products" on public.products;
create policy "Users manage their own products" on public.products for all to authenticated using ((select auth.uid())=owner_id) with check ((select auth.uid())=owner_id);
drop policy if exists "Users manage their own orders" on public.orders;
create policy "Users manage their own orders" on public.orders for all to authenticated using ((select auth.uid())=owner_id) with check ((select auth.uid())=owner_id);
create index if not exists products_owner_created_idx on public.products(owner_id,created_at desc);
create index if not exists orders_owner_created_idx on public.orders(owner_id,created_at desc);
